import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { registerSW } from 'virtual:pwa-register';
import App from './App';
import './index.css';

// Cache the app so it opens with no signal; update quietly when a new version is published.
registerSW({ immediate: true });

// Ask the browser not to clear our offline data when the phone is short of space.
navigator.storage?.persist?.().catch(() => undefined);

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <App />
  </StrictMode>,
);
